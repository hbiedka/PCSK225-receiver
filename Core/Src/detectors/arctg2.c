uint32_t arctg2(int32_t y, int32_t x)
{
	//deal with (0,0) coords
	if (!x && !y) return 0;

	uint32_t abs_y = abs(y);
	uint32_t abs_x = abs(x);

	uint32_t angle = 0;

	// this is div-by-zero-safe by design
	// if |y| > |x|, then if x = 0, then y >= 1
	// if not, then |x| >= |y|, which means
	// - if y is >0, then x is also >0, which means >= 1
	// - if y is 0, then x >= 0
	// 	- but it can't be 0 because it will return 0 at the very beggining of fcn

	if (abs_y > abs_x) {
		uint64_t index = abs_x*ATAN_LUT_SIZE/abs_y;
		//swap to pi/2 - angle
		index &= ATAN_LUT_SIZE_MASK;
		angle = ATAN_HALF_PI-atan_lut[index];
	} else {
		uint64_t index = abs_y*ATAN_LUT_SIZE/abs_x;
		index &= ATAN_LUT_SIZE_MASK;
		angle = atan_lut[index];
	}

	// quadrant correction
	if (x < 0) {
		if (y < 0) {
			// 3rd quadrant
			angle += ATAN_PI;
		} else {
			// 2nd quadrant
			angle = ATAN_PI - angle;
		}
	} else if (y < 0) {
		angle = -angle;	// equals to 2pi-angle if 2pi is 2^32
	}
	return angle;
}

uint32_t IQarctg2(struct IQ *iq) {
	return arctg2(iq->q,iq->i);
}

